/// The kart as the game's selection screen names it: body, tires and glider ("Torbellino · Leaf · Superala"); unknown parts are left out
String kartName(int? body, int? tires, int? glider) => [
  listName(_bodies, body),
  listName(_tires, tires),
  listName(_gliders, glider),
].where((s) => s.isNotEmpty).join(' · ');
