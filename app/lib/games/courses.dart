// The console a retro course came from, by its folder's prefix (G: the original courses, D: the DLC, B: battle; u is a new course)
const _consoles = {
  'wii': 'Wii',
  'agb': 'GBA',
  'ds': 'DS',
  '3ds': '3DS',
  '64': 'N64',
  'sfc': 'SNES',
  'gc': 'GCN',
};
final _prefix = RegExp(r'^[GDB]([a-z0-9]+)_');

/// The Spanish name the game shows for a course folder ("Gu_WaterPark" → "Parque Acuático"); empty for none
String courseName(String id) {
  if (id.isEmpty) return '';
  final key = id.startsWith('Du_Animal') ? 'Du_Animal' : id; // one per season
  final name = _names[key];
  if (name == null) return id.replaceAll('_', ' ');
  final console = _consoles[_prefix.firstMatch(key)?.group(1)];
  return console == null ? name : '$console $name';
}
